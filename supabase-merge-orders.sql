WITH checks AS (

  -- Check 1: Cột parent_order_no tồn tại
  SELECT
    1 AS num,
    'Cot parent_order_no ton tai' AS name,
    CASE
      WHEN EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema='public' AND table_name='orders'
          AND column_name='parent_order_no' AND data_type='text'
      ) THEN 'PASS' ELSE 'FAIL'
    END AS status,
    'orders.parent_order_no TEXT' AS detail

  UNION ALL

  -- Check 2: Cột is_merged tồn tại + default false
  SELECT
    2,
    'Cot is_merged ton tai voi default false',
    CASE
      WHEN EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema='public' AND table_name='orders'
          AND column_name='is_merged'
          AND data_type='boolean'
          AND column_default = 'false'
      ) THEN 'PASS' ELSE 'FAIL'
    END,
    'orders.is_merged BOOLEAN DEFAULT false'

  UNION ALL

  -- Check 3: FK constraint parent_order_no → orders(order_no)
  SELECT
    3,
    'FK constraint parent_order_no -> orders(order_no)',
    CASE
      WHEN EXISTS (
        SELECT 1
        FROM information_schema.table_constraints tc
        JOIN information_schema.referential_constraints rc
          ON rc.constraint_name = tc.constraint_name
        JOIN information_schema.key_column_usage kcu
          ON kcu.constraint_name = tc.constraint_name
        WHERE tc.table_name='orders'
          AND tc.constraint_type='FOREIGN KEY'
          AND kcu.column_name='parent_order_no'
      ) THEN 'PASS' ELSE 'FAIL'
    END,
    'REFERENCES public.orders(order_no) ON DELETE SET NULL'

  UNION ALL

  -- Check 4: Index idx_orders_parent tồn tại
  SELECT
    4,
    'Index idx_orders_parent ton tai',
    CASE
      WHEN EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE tablename='orders' AND indexname='idx_orders_parent'
      ) THEN 'PASS' ELSE 'FAIL'
    END,
    'CREATE INDEX idx_orders_parent ... WHERE parent_order_no IS NOT NULL'

  UNION ALL

  -- Check 5: Function add_to_existing_order tồn tại + SECURITY DEFINER
  SELECT
    5,
    'Function add_to_existing_order ton tai + SECURITY DEFINER',
    CASE
      WHEN EXISTS (
        SELECT 1
        FROM pg_proc p
        JOIN pg_namespace ns ON ns.oid = p.pronamespace
        WHERE ns.nspname='public'
          AND p.proname='add_to_existing_order'
          AND p.prosecdef = true  -- SECURITY DEFINER flag
      ) THEN 'PASS' ELSE 'FAIL'
    END,
    'SECURITY DEFINER xac nhan'

  UNION ALL

  -- Check 6: authenticated có EXECUTE
  SELECT
    6,
    'authenticated co EXECUTE tren function',
    CASE
      WHEN EXISTS (
        SELECT 1
        FROM information_schema.routine_privileges
        WHERE routine_schema='public'
          AND routine_name='add_to_existing_order'
          AND grantee='authenticated'
          AND privilege_type='EXECUTE'
      ) THEN 'PASS' ELSE 'FAIL'
    END,
    'GRANT EXECUTE TO authenticated'

  UNION ALL

  -- Check 7: anon KHÔNG có EXECUTE
  SELECT
    7,
    'anon KHONG co EXECUTE tren function',
    CASE
      WHEN NOT EXISTS (
        SELECT 1
        FROM information_schema.routine_privileges
        WHERE routine_schema='public'
          AND routine_name='add_to_existing_order'
          AND grantee='anon'
          AND privilege_type='EXECUTE'
      ) THEN 'PASS' ELSE 'FAIL'
    END,
    'REVOKE EXECUTE FROM anon xac nhan'

  UNION ALL

  -- Check 8: Có ít nhất 1 đơn gốc (parent_order_no IS NULL) — data integrity
  SELECT
    8,
    'Co don goc (parent_order_no IS NULL) trong orders',
    CASE
      WHEN EXISTS (
        SELECT 1 FROM public.orders WHERE parent_order_no IS NULL LIMIT 1
      ) THEN 'PASS' ELSE 'WARN: Bang orders rong (OK neu moi deploy)'
    END,
    (SELECT COALESCE('order_no=' || MAX(order_no), 'bang rong')
     FROM public.orders WHERE parent_order_no IS NULL)

)

SELECT
  num    AS "#",
  status AS "STATUS",
  name   AS "CHECK",
  detail AS "DETAIL"
FROM checks
ORDER BY num;

